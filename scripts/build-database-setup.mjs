import { readFile, readdir, writeFile } from 'node:fs/promises';

// SQL Editor fallback for installing this app in an empty project. The normal
// deployment path remains `supabase db push` after CLI authentication/linking.
const root = new URL('../supabase/', import.meta.url);
const files = (await readdir(new URL('migrations/', root))).filter(name => /^\d+_.+\.sql$/.test(name)).sort();
const quote = value => `'${value.replaceAll("'", "''")}'`;
let sql = `-- Generated by npm run backend:sql. Do not edit: edit the migrations instead.
-- Install in the Supabase SQL Editor of your EMPTY Pigeon Post project.
-- All schema changes and migration history commit together or roll back.
-- This is not an upgrade script; use the CLI for later migrations.
begin;
set local lock_timeout = '10s';
set local statement_timeout = '60s';
do $preflight$
begin
  if exists (select 1 from pg_tables where schemaname in ('public', 'private')) then
    raise exception 'This project already has application tables. Setup stopped without changes. Use the migration CLI for upgrades.';
  end if;
  if exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'private') then
    raise exception 'The private schema already contains functions. Setup stopped without changes.';
  end if;
end
$preflight$;

create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations (version text primary key);
alter table supabase_migrations.schema_migrations add column if not exists name text;
alter table supabase_migrations.schema_migrations add column if not exists statements text[];
revoke all on schema supabase_migrations from public, anon, authenticated;
revoke all on table supabase_migrations.schema_migrations from public, anon, authenticated;
`;
for (const file of files) {
  const contents = await readFile(new URL(`migrations/${file}`, root), 'utf8');
  const [, version, name] = file.match(/^(\d+)_(.+)\.sql$/);
  sql += `\n-- BEGIN ${file}\n${contents}\n-- END ${file}\n`;
  sql += `insert into supabase_migrations.schema_migrations(version, name, statements) values (${quote(version)}, ${quote(name)}, array[${quote(contents)}]);\n`;
}
sql += `\nnotify pgrst, 'reload schema';\ncommit;\nselect public.backend_status();\n`;
await writeFile(new URL('setup.sql', root), sql);
console.log(`Generated supabase/setup.sql from ${files.length} migrations. Apply once to an empty app database.`);
